#!/usr/bin/env python3
"""Write the appendix's paired-comparison table from experiments/outputs.

Rows are the methods in hero/results.json `comparisons`, in registry order; cells are HERD minus
the method after the last stage with the 95% paired item-bootstrap interval, for the five stream
quantities of Table 1. Bold marks an interval that excludes zero. No number is written here.

    python3 experiments/code/paper-comparison-table.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "experiments/outputs"
TABLE = ROOT / "output/paper/tables/comparisons.tex"

COLUMNS = [  # (header, comparisons key)
    (r"$\Delta$AA", "seenMean"),
    (r"$\Delta$Acq.", "acquisition"),
    (r"$\Delta$F", "forgetting"),
    (r"$\Delta$BWT", "signedBWT"),
    (r"$\Delta$G-test", "generalMacro"),
]
FAMILIES = {"control": "Control", "non-parametric": "Context", "parametric": "Weights", "hybrid": "Hybrid"}


def read(path: Path):
    return json.loads(path.read_text())


def signed(value: float, digits: int = 3) -> str:
    text = f"{abs(value):.{digits}f}"
    return f"$-${text}" if value < 0 else f"$+${text}"


def bound(value: float, digits: int = 3) -> str:
    text = f"{abs(value):.{digits}f}"
    return f"$-${text}" if value < 0 else text


def main() -> None:
    registry = read(OUT / "schema.json")["registry"]
    hero = read(OUT / "hero/results.json")
    comparisons = hero["comparisons"]
    by_id = {m["id"]: m for m in comparisons["methods"]}
    rows = []
    for entry in registry:
        if entry["id"] not in by_id:
            continue
        rows.append({
            "id": entry["id"], "family": entry["family"],
            "short": read(OUT / entry["path"] / "method.json")["short"],
            "comparison": by_id[entry["id"]],
        })

    lines = [
        "% Generated by experiments/code/paper-comparison-table.py from experiments/outputs; do not edit by hand.",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{l" + "c" * len(COLUMNS) + "}",
        r"\toprule",
        " & ".join(["Baseline", *(c[0] for c in COLUMNS)]) + r" \\",
        r"\midrule",
    ]
    previous = None
    for r in rows:
        if previous is not None and r["family"] != previous:
            lines.append(r"\midrule")
        previous = r["family"]
        cells = []
        for _, key in COLUMNS:
            c = r["comparison"][key]
            low, high = c["interval"]
            text = rf"{signed(c['difference'])}\,{{\scriptsize[{bound(low)}, {bound(high)}]}}"
            if low > 0 or high < 0:
                text = rf"\textbf{{{text}}}"
            cells.append(text)
        lines.append(" & ".join([r["short"], *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines))
    print(f"wrote {TABLE.relative_to(ROOT)} ({len(rows)} baselines, stage {comparisons['stage']}, "
          f"{comparisons['level']:.0%} intervals, {comparisons['draws']} draws)")


if __name__ == "__main__":
    main()

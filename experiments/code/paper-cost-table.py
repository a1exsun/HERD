#!/usr/bin/env python3
"""Write the appendix's cost table from experiments/outputs.

One row per learning method in registry order, HERD first: training seconds at the first and
last stage and in total (accounting[].training.seconds, cost), and the context the deployed
predictor attaches to every prompt at inference (state.tokens for a harness or playbook; nothing
for weights-only predictors and for HERD, which deploys bare weights). Hardware differs across
methods and is listed per method in Appendix B, so seconds compare within a row and across rows
of the same hardware only; the caption says so. No number is written here.

    python3 experiments/code/paper-cost-table.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "experiments/outputs"
TABLE = ROOT / "output/paper/tables/cost.tex"

HARDWARE = [("A100", "A100"), ("H200", "H200"), ("A40", "A40"), ("M4 Max", "M4")]
FAMILIES = {"non-parametric": "Context", "parametric": "Weights", "hybrid": "Hybrid", "ours": "This work"}


def read(path: Path):
    return json.loads(path.read_text())


def hardware(text: str) -> str:
    found = sorted(((text.find(k), label) for k, label in HARDWARE if k in text))
    return ", ".join(label for _, label in found) or text


def seconds(value) -> str:
    if isinstance(value, dict):
        value = value.get("value")
    return "--" if value is None else f"{value:,.0f}"


def main() -> None:
    rows = []
    for entry in read(OUT / "schema.json")["registry"]:
        directory = OUT / entry["path"]
        if "tier" in entry or entry["family"] == "control" or not (directory / "results.json").is_file():
            continue
        results = read(directory / "results.json")
        accounting = results.get("accounting") or []
        stages = {a["stage"]: a["training"].get("seconds") for a in accounting if "training" in a}
        state = results.get("state") or {}
        context = state.get("tokens") if state.get("kind") in {"playbook", "harness"} else 0
        rows.append({
            "id": entry["id"], "family": entry["family"], "short": read(directory / "method.json")["short"],
            "hardware": hardware(results["cost"]["hardware"]),
            "first": stages.get(min(stages)) if stages else None,
            "last": stages.get(max(stages)) if stages else None,
            "total": results["cost"].get("trainingSeconds"),
            "context": context,
        })
    rows = [r for r in rows if r["family"] == "ours"] + [r for r in rows if r["family"] != "ours"]

    lines = [
        "% Generated by experiments/code/paper-cost-table.py from experiments/outputs; do not edit by hand.",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Method & \multicolumn{3}{c}{Training time (s)} & Context \\",
        r"\cmidrule(lr){2-4}",
        r" & stage 1 & stage 25 & total & tokens \\",
        r"\midrule",
    ]
    previous = None
    for r in rows:
        if previous is not None and r["family"] != previous:
            lines.append(r"\midrule")
        previous = r["family"]
        label = rf"\textbf{{{r['short']}}}" if r["family"] == "ours" else r["short"]
        context = "0" if not r["context"] else f"{r['context']:,}"
        lines.append(" & ".join([label, seconds(r["first"]), seconds(r["last"]), seconds(r["total"]), context]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines))
    print(f"wrote {TABLE.relative_to(ROOT)} ({len(rows)} methods)")


if __name__ == "__main__":
    main()

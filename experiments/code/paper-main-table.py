#!/usr/bin/env python3
"""Write the paper's main results table (Table 1) from experiments/outputs.

The rows, columns, order, rounding and bold marks follow the project page's main comparison
(apps/hero-official-website/src/sections/Experiments.tsx, `Comparison` at depth 25): HERD first,
then every registry method with a results.json in registry order (ablations, which carry a `tier`,
are left to the ablation table); three decimals, means only (the page's ± spreads are left out);
bold marks the best learning method (not a control) in each column.

    python3 experiments/code/paper-main-table.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "experiments/outputs"
TABLE = ROOT / "output/paper/tables/main-results.tex"
DEPTH = "25"

FAMILIES = {"control": "Control", "non-parametric": "Context", "parametric": "Weights", "hybrid": "Hybrid", "ours": "This work"}
# (header, better, value, signed); the same columns as the project page, in the paper's notation.
COLUMNS = [
    (r"AA$\uparrow$", "high", lambda d: d["seenMean"], False),
    (r"Acq.$\uparrow$", "high", lambda d: d["acquisition"], False),
    (r"F$\downarrow$", "low", lambda d: d["forgetting"], False),
    (r"BWT$\uparrow$", "high", lambda d: d["signedBWT"], True),
    (r"G-test$\uparrow$", "high", lambda d: d["general"]["macro"], False),
    (r"$\Delta C\uparrow$", "high", lambda d: d["general"]["change"], True),
    (r"$\Delta C_{\min}\uparrow$", "high", lambda d: d["general"]["worstCategoryChange"], True),
]


def read(path: Path):
    return json.loads(path.read_text())


def number(value: float, signed: bool) -> str:
    text = f"{abs(value):.3f}"
    if signed and value > 0:
        return f"$+${text}"
    if value < 0:
        return f"$-${text}"
    return text


def methods() -> list[dict]:
    rows = []
    for entry in read(OUT / "schema.json")["registry"]:
        directory = OUT / entry["path"]
        if "tier" in entry or not (directory / "results.json").is_file():
            continue
        results = read(directory / "results.json")
        rows.append({
            "id": entry["id"],
            "short": read(directory / "method.json")["short"],
            "family": entry["family"],
            "depth": results["summary"]["depths"][DEPTH],
        })
    return [r for r in rows if r["id"] == "hero"] + [r for r in rows if r["id"] != "hero"]


def main() -> None:
    rows = methods()
    learners = [r for r in rows if r["family"] != "control"]
    best = [(max if better == "high" else min)(get(r["depth"]) for r in learners) for _, better, get, _ in COLUMNS]

    lines = [
        "% Generated by experiments/code/paper-main-table.py from experiments/outputs; do not edit by hand.",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{ll" + "c" * len(COLUMNS) + "}",
        r"\toprule",
        " & ".join(["Method", "Family", *(c[0] for c in COLUMNS)]) + r" \\",
        r"\midrule",
    ]
    previous = None
    for r in rows:
        if previous is not None and r["family"] != previous:
            lines.append(r"\midrule")
        previous = r["family"]
        cells = []
        for (_, _, get, signed), top in zip(COLUMNS, best):
            value = get(r["depth"])
            text = number(value, signed)
            if r["family"] != "control" and abs(value - top) < 5e-7:
                text = rf"\textbf{{{text}}}"
            cells.append(text)
        name = rf"\textbf{{{r['short']}}}" if r["id"] == "hero" else r["short"]
        lines.append(" & ".join([name, FAMILIES[r["family"]], *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines))
    print(f"wrote {TABLE.relative_to(ROOT)} ({len(rows)} methods, stage {DEPTH})")


if __name__ == "__main__":
    main()
